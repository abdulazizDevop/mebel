"""Consent endpoints (152-ФЗ ст. 9, 38-ФЗ ст. 18).

Write model: append-only. Customers can *add* a decision or *withdraw* one;
nothing here edits or deletes an existing row, so the history stays trustworthy.
"""
from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, Request, status
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.database import get_db
from app.deps import CurrentCustomer, get_optional_customer
from app.legal import ConsentType
from app.models import Customer
from app.models.consent import ConsentLog
from app.rate_limit import limiter
from app.schemas.consent import ConsentIn, ConsentOut, ConsentWithdrawIn, ConsentWithdrawOut
from app.services.consent import record_consent, revoke_consents

router = APIRouter(prefix="/consents", tags=["consents"])


@router.post("", response_model=ConsentOut, status_code=status.HTTP_201_CREATED)
@limiter.limit("30/minute")
def create_consent(
    request: Request,
    payload: ConsentIn,
    db: Annotated[Session, Depends(get_db)],
    customer: Annotated[Customer | None, Depends(get_optional_customer)],
):
    """Record a cookie or marketing decision. Anonymous visitors identify
    themselves with a random `request_id` generated by the browser."""
    if customer is None and not payload.request_id:
        raise HTTPException(status_code=400, detail="request_id is required for anonymous consents")

    ct = ConsentType(payload.consent_type)
    if ct == ConsentType.marketing and customer is not None and not payload.granted:
        # Opting out supersedes earlier opt-ins — keep the history consistent.
        revoke_consents(db, customer_id=customer.id, consent_type=ct)

    row = record_consent(
        db,
        consent_type=ct,
        granted=payload.granted,
        source_form=payload.source_form,
        customer_id=customer.id if customer else None,
        request_id=payload.request_id,
        document_version=payload.document_version,
        request=request,
    )
    if ct == ConsentType.marketing and customer is not None:
        customer.marketing_allowed = payload.granted
    db.commit()
    db.refresh(row)
    return row


@router.get("/me", response_model=list[ConsentOut])
def my_consents(customer: CurrentCustomer, db: Annotated[Session, Depends(get_db)]):
    """Read-only view of the caller's own consent history."""
    rows = db.execute(
        select(ConsentLog)
        .where(ConsentLog.customer_id == customer.id)
        .order_by(ConsentLog.created_at.desc())
    ).scalars().all()
    return rows


@router.post("/withdraw", response_model=ConsentWithdrawOut)
@limiter.limit("10/minute")
def withdraw(
    request: Request,
    payload: ConsentWithdrawIn,
    customer: CurrentCustomer,
    db: Annotated[Session, Depends(get_db)],
):
    """Withdraw marketing or personal-data consent (152-ФЗ ст. 9 ч. 2).

    Marketing → `marketing_allowed = false` immediately (spec §32).
    Personal data → rows revoked; data still required to perform existing
    orders / legal obligations is kept on those separate legal bases (ст. 6
    ч. 1 п. 2, 5) — the account itself is removed via /auth/customer/me/delete.
    """
    ct = ConsentType(payload.consent_type)
    revoked = revoke_consents(db, customer_id=customer.id, consent_type=ct)
    if ct == ConsentType.marketing:
        customer.marketing_allowed = False
    db.commit()
    return ConsentWithdrawOut(consent_type=ct.value, revoked=revoked, marketing_allowed=bool(customer.marketing_allowed))
